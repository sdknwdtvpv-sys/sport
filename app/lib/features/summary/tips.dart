/// 这一次训练该看哪一条（**纯函数**：同一个 [workoutId] 永远给同一条）。
///
/// 用 id 的哈希而不是"随机"：总结屏重建（比如改了一下笔记）时，
/// 那一条**不能变** —— 每次刷新都换一句，读起来就像在抽卡。
Tip tipFor(String workoutId) {
  if (kTips.isEmpty) {
    return const Tip(id: 'none', title: '', body: '');
  }
  // 用累加而不是 `hashCode`：Dart 的 `String.hashCode` 在不同进程/版本上不保证稳定，
  // 而"同一个 id 给同一条"是要被测试钉住的（跨运行也必须成立）。
  int h = 0;
  for (final int c in workoutId.codeUnits) {
    h = (h * 31 + c) & 0x7fffffff;
  }
  return kTips[h % kTips.length];
}
