/// 总结屏之后一条 **15 秒读完**的小知识。三条纪律：
///   1. **内置文案表，不联网**（第二部分的三条红线第 1 条：数据不出设备）；
///   2. **挑哪一条是纯函数**（按这次训练的 id 取模）—— 同一屏刷新两次看到的
///      必须是同一条，而且能被单测钉住（"每次都随机换一句"会让用户以为 App 在抽卡）；
///   3. **只讲已经确定的事**：每条都是训练常识，不承诺效果、不涉及伤病诊断
