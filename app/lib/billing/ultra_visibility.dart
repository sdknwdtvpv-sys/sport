/// 练了么 · **Ultra（会员）在首版是否上架**（2026-10-11）
///
/// 用户拍板：**v1.67.x 走"免费版先上"** —— 首版不卖会员。
/// 于是 Ultra 的三个入口在整个 App 里关闭，但**代码留着**。
///
/// 为什么是"一个常量 + 默认关"，而不是"把入口删掉"：
///   * 会员那一套（权益内核 + 会员页 + 进阶分析 + 批量整理）**已经做完并测过**，
///     只是**首版不卖**（先拿首波流量验证留存，会员随下一版开）。
///     删掉入口等于把做完的东西藏进 git 历史，下一版要重写一遍；
///   * 而"有开关但默认关"最大的风险是**悄悄烂掉**（开关打开时那几屏早就画不出来了）。
///     所以有一条判据同时守两头：`app/test/ultra_release_gate_test.dart`
///     ① 默认（= 发版）状态下三个入口**一个都不渲染**；
///     ② `showUltra: true` 时它们**真的会回来**。
///
/// ⚠️ **为什么首版必须关掉它（而不是"反正没人点"）**：
/// release 包**拿不到商品**（真内购在 M2），于是那个会员页在审核员手里是这样一副样子 ——
/// 「练了么 Ultra」摆着权益清单与三档商品的空位、写着"暂时获取不到商品信息"，
/// 「恢复购买 / 管理订阅」点下去只弹一句"内购正在接入"。
/// 那是**半成品入口**：Apple 审核指南 2.1（功能不完整）与 3.1.1（购买入口必须走 IAP）
/// 都能据此拒。首版免费、会员下一版，是风险最小、最快上架的那条路。
///
/// 翻开它（M2 真内购落地时）要同时做三件事：
///   1. 把下面这个常量改成 `true`；
///   2. `ultra_release_gate_test.dart` 里那三条"默认不渲染"的断言会红 ——
///      那是**故意的**（它逼你回来确认"这一版真的要卖了"），改成断言渲染；
///   3. `docs/store-listing-ios.md` 的「价格 / 内购」两行与审核备注、App Privacy 表，
///      以及 `docs/plan-membership-2026-10-10.md` 的 §十一 一起更新。
